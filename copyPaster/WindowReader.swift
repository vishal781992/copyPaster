import SwiftUI

/// Hands back the NSWindow hosting a SwiftUI view (the popover's window, or a regular window).
/// The window only exists once the view is on screen, so it's reported after layout.
struct WindowReader: NSViewRepresentable {
    @Binding var window: NSWindow?

    func makeNSView(context: Context) -> NSView {
        let view = NSView()
        DispatchQueue.main.async { window = view.window }
        return view
    }

    func updateNSView(_ nsView: NSView, context: Context) {
        DispatchQueue.main.async {
            if window !== nsView.window { window = nsView.window }
        }
    }
}
